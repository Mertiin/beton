//! 5×7 ASCII atlas for names and the HUD.

use beton::Font;

pub fn make_font(texture: beton::TextureId) -> Font {
    Font::grid(texture, 16, 6, ' ')
}

pub fn atlas_rgba() -> (Vec<u8>, u32, u32) {
    const CW: u32 = 8;
    const CH: u32 = 12;
    const COLS: u32 = 16;
    const ROWS: u32 = 6;
    let w = CW * COLS;
    let h = CH * ROWS;
    let mut rgba = vec![0u8; (w * h * 4) as usize];
    for code in 32u8..128 {
        let idx = (code - 32) as u32;
        let col = idx % COLS;
        let row = idx / COLS;
        let ox = col * CW;
        let oy = row * CH;
        let glyph = glyph5x7(code);
        for gy in 0..7u32 {
            for gx in 0..5u32 {
                if (glyph[gy as usize] & (1 << (4 - gx))) == 0 {
                    continue;
                }
                let x = ox + 1 + gx;
                let y = oy + 2 + gy;
                let i = ((y * w + x) * 4) as usize;
                rgba[i] = 255;
                rgba[i + 1] = 255;
                rgba[i + 2] = 255;
                rgba[i + 3] = 255;
            }
        }
    }
    (rgba, w, h)
}

